/**
 * @brief Временное окно, за которое запрашивается отчёт о продажах,
 *        относительно заданной опорной даты (см. Pharmacy::GetSalesForPeriod).
 */
enum class SalesPeriod {
    Week,   ///< Последние 7 дней вплоть до опорной даты включительно.
    Month,  ///< Последние 30 дней вплоть до опорной даты включительно.
    Year    ///< Последние 365 дней вплоть до опорной даты включительно.
};
